def short(x):
    return f"SAR {x / 1e6:.2f}M" if abs(x) >= 1e6 else f"SAR {x / 1e3:.0f}k"


def card(col, label, value, note, level=None):
    border = COLORS.get(level, "#E5E7EB")
    col.markdown(
        f"""<div style="border:1px solid #E5E7EB;border-top:4px solid {border};border-radius:8px;padding:10px 12px;min-height:118px">
        <div style="font-size:0.78rem;color:#6B7280">{label}</div>
        <div style="font-size:1.3rem;font-weight:600;margin:2px 0;white-space:nowrap">{value}</div>
        <div style="font-size:0.78rem;color:#6B7280">{note}</div></div>""",
        unsafe_allow_html=True)


