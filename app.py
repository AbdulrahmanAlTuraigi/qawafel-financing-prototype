@st.cache_data
def load(amount, term):
    return engine.run(INVOICES, BANK, COMPANY, amount=amount, term=term)


def sar(x):
    return f"SAR {x:,.0f}"


@st.cache_data
def sample_zip():
    """The raw files exactly as the SME would upload them, so reviewers can compare them with the cleaned view."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for path in [INVOICES, BANK, COMPANY]:
            z.write(path, os.path.basename(path))
        statements = os.path.join(DATA, "bank_statements")
        for name in sorted(os.listdir(statements)):
            z.write(os.path.join(statements, name), f"bank_statements/{name}")
    return buf.getvalue()


